#!/usr/bin/env python3
"""Decrypt the exe's XOR-encrypted string literals: analysis/<build>/strings_encrypted.tsv.

    python3 tools/strings_encrypted.py <unpacked exe> [<build>]

TU67 keeps many string literals encrypted until first use: an 8-byte key, then a u32 whose low 24 bits are the
length and whose top byte is 1 while still encrypted, then the bytes XORed with the key (key byte i & 7). The code
decrypts in place on first use and clears the top byte (e.g. 1465F7490 naming its GPU buffers, 146590C50).
Scanning .data and .rdata for that shape (length 2-120, top byte 1, non-zero key) and keeping results that decrypt to
printable text finds them; each row is the address of the key and the text. The names say what the code using
them is for ("regularPatchIndices", "Unified Vertex Page Table", ...).
"""
import struct
import sys
from pathlib import Path

import pefile

ROOT = Path(__file__).resolve().parents[1]


def scan(exe):
    pe = pefile.PE(exe, fast_load=True)
    base = pe.OPTIONAL_HEADER.ImageBase
    for s in pe.sections:
        if s.Name.rstrip(b'\0') not in (b'.data', b'.rdata'):
            continue
        d = s.get_data()
        for o in range(0, len(d) - 16, 4):
            v = struct.unpack_from('<I', d, o + 8)[0]
            n = v & 0xFFFFFF
            if v >> 24 != 1 or not 2 <= n <= 120 or o + 12 + n > len(d):
                continue
            key = d[o:o + 8]
            if key == bytes(8):
                continue
            t = bytes(c ^ key[i & 7] for i, c in enumerate(d[o + 12:o + 12 + n])).split(b'\0')[0]
            if len(t) >= 3 and all(32 <= c < 127 for c in t):
                yield base + s.VirtualAddress + o, t.decode()


def main():
    exe = sys.argv[1]
    build = sys.argv[2] if len(sys.argv) > 2 else 'ModernWarfare_TU67'
    rows = list(scan(exe))
    out = ROOT / 'analysis' / build / 'strings_encrypted.tsv'
    out.write_text('# GENERATED by tools/strings_encrypted.py. Do not edit.\naddress\ttext\n' +
                   ''.join(f'{a:X}\t{t}\n' for a, t in rows))
    print(f'{len(rows)} encrypted strings -> {out}')


if __name__ == '__main__':
    main()
