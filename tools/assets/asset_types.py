#!/usr/bin/env python3
"""Generate analysis/<build>/assets/asset_types.tsv: every XAssetType with its zone loader and header size.

    python3 tools/assets/asset_types.py <build> <unpacked exe> --names <VA> --dispatcher <VA>

For TU67: --names 147627730 --dispatcher 142E2ECF0. The unpacked exe is tools/unpack/arxan.py's output (its sha256 is
pinned in target.toml); the pseudocode comes from the published analysis/<build>/pseudocode.

How each column is found (docs/assets/zones.md 6):
  name        the asset-type name table (122 string pointers, enum order)
  ptr_loader  the dispatcher is a chain of `if (type == N) { Load_<T>Ptr(); ... }`: the function called for N
  struct_loader  in Load_<T>Ptr, the first `FUN_x(0|1)` after the block push `FUN_142df1380(<block>)`
  block       that pushed stream block
  header_size the size the struct loader passes to the stream read 143760AE0 (its R8D immediate), read from the
              exe's code because the decompiler drops that argument in some loaders
Types the dispatcher has no case for are listed with empty loader columns.
"""
import re
import struct
import sys
from pathlib import Path

import pefile
from capstone import CS_ARCH_X86, CS_MODE_64, Cs

ROOT = Path(__file__).resolve().parents[2]
BASE = 0x140000000
STREAM_READ = 0x143760AE0     # DB_LoadXFileData-like: (atStreamStart, ptr, size)
PUSH_BLOCK = "142df1380"
TYPE_COUNT = 122


def pseudocode(build: str, va: int) -> str:
    f = ROOT / "analysis" / build / "pseudocode" / "_unattributed" / f"{va >> 20:X}0000.c"
    text = f.read_text(errors="replace")
    head = f"// {va:09X} "
    i = text.index(head)
    j = re.compile(r"^// [0-9A-F]{9} ", re.M).search(text, i + len(head))
    return text[i:j.start() if j else len(text)]


def main():
    build, exe = sys.argv[1], sys.argv[2]
    names_va = int(sys.argv[sys.argv.index("--names") + 1], 16)
    disp_va = int(sys.argv[sys.argv.index("--dispatcher") + 1], 16)
    pe = pefile.PE(exe, fast_load=True)
    data = pe.__data__
    md = Cs(CS_ARCH_X86, CS_MODE_64)

    def rd(va, n):
        o = pe.get_offset_from_rva(va - BASE)
        return bytes(data[o:o + n])

    def cstr(va):
        return rd(va, 128).split(b"\0")[0].decode("latin-1")

    names = [cstr(struct.unpack("<Q", rd(names_va + 8 * i, 8))[0]) for i in range(TYPE_COUNT)]

    def header_size(fva):
        r8 = None
        for ins in md.disasm(rd(fva, 0x300), fva):
            ops = [o.strip() for o in ins.op_str.split(",")]
            if ins.mnemonic == "mov" and ops[0] in ("r8d", "r8") and ops[-1].startswith("0x"):
                r8 = int(ops[-1], 16)
            if ins.mnemonic in ("call", "jmp") and ins.op_str == hex(STREAM_READ):
                return r8
            if ins.mnemonic == "ret":
                return None
        return None

    disp = pseudocode(build, disp_va)
    cases = re.findall(r"if \(iVar\d+ == (0x[0-9a-f]+|\d+)\) \{\s*(?:DAT_[0-9a-f]+ = [^;]+;\s*)?FUN_([0-9a-f]+)\(\);", disp)
    rows = {}
    for t, ptr in cases:
        t, ptr = int(t, 0), int(ptr, 16)
        body = pseudocode(build, ptr)
        m = re.search(rf"FUN_{PUSH_BLOCK}\((0x[0-9a-f]+|\d+)\);.*?\n\s*FUN_([0-9a-f]+)\((?:0|1)\);", body, re.S)
        if not m:
            raise SystemExit(f"type {t}: no struct loader found in {ptr:09X}")
        block, sl = int(m.group(1), 0), int(m.group(2), 16)
        size = header_size(sl)
        if size is None:
            raise SystemExit(f"type {t}: no header size found in {sl:09X}")
        rows[t] = (f"{ptr:09X}", f"{sl:09X}", str(block), f"{size:#x}")

    out = ROOT / "analysis" / build / "assets" / "asset_types.tsv"
    out.parent.mkdir(parents=True, exist_ok=True)
    lines = [f"# GENERATED by tools/assets/asset_types.py {build} <unpacked exe> --names {names_va:09X} "
             f"--dispatcher {disp_va:09X}. Do not edit.",
             "type\tname\tptr_loader\tstruct_loader\tblock\theader_size"]
    for t in range(TYPE_COUNT):
        lines.append("\t".join([str(t), names[t], *rows.get(t, ("", "", "", ""))]))
    out.write_text("\n".join(lines) + "\n")
    print(f"{out.relative_to(ROOT)}: {len(rows)} of {TYPE_COUNT} types dispatched")


if __name__ == "__main__":
    main()
